def detect_lang() -> str:
    for var in ("LC_ALL", "LC_MESSAGES", "LANG"):
        raw = os.environ.get(var, "")
        if not raw:
            continue
        if _is_c(raw):
            return "en"
        break
    language = os.environ.get("LANGUAGE", "")
    if language:
        for part in language.split(":"):
            code = _normalize(part)
            if code:
                return code
    for var in ("LC_ALL", "LC_MESSAGES", "LANG"):
        raw = os.environ.get(var, "")
        if not raw or _is_c(raw):
            continue
        code = _normalize(raw)
        if code:
            return code
    return "en"


def t(lang: str, key: str, *, voice: str = "pro", **kwargs: object) -> str:
    text = moe_lookup(lang, key) if voice == "moe" else None
    if text is None:
        table = _STRINGS.get(lang) or _STRINGS["en"]
        text = table.get(key) or _STRINGS["en"].get(key, key)
    if kwargs:
        return text.format(**kwargs)
    return text


def _is_c(tag: str) -> bool:
    token = tag.strip().replace("-", "_").split(".")[0].lower()
    return token in ("c", "posix")


def _normalize(tag: str) -> str | None:
    token = tag.strip().replace("-", "_").split(".")[0].lower()
    if not token or _is_c(token):
        return None
    primary = token.split("_", 1)[0]
    if primary in LANGS:
        return primary
    return None
